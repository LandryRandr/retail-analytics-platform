
-- VIEW - GOLD.V_SALES
CREATE OR REPLACE VIEW RETAIL_ANALYTICS.GOLD.V_SALES AS
SELECT
    f.ORDER_ID,
    f.ORDER_DATE,
    f.YEAR,
    f.QUARTER,
    f.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME,
    c.COUNTRY,
    f.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.CATEGORY,
    f.QUANTITY,
    f.UNIT_PRICE,
    f.TOTAL_AMOUNT
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES f
LEFT JOIN RETAIL_ANALYTICS.GOLD.DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN RETAIL_ANALYTICS.GOLD.DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID;



-- V_SALES_BY_PRODUCT
CREATE OR REPLACE VIEW RETAIL_ANALYTICS.GOLD.V_SALES_BY_PRODUCT AS
SELECT
    f.PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    SUM(QUANTITY) AS UNITS_SOLD,
    SUM(TOTAL_AMOUNT) AS TOTAL_SALES
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES f
JOIN RETAIL_ANALYTICS.GOLD.DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
GROUP BY
    f.PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY;



-- V_SALES_BY_MONTH
CREATE OR REPLACE VIEW RETAIL_ANALYTICS.GOLD.V_SALES_BY_MONTH AS
SELECT
    YEAR,
    MONTH(ORDER_DATE) AS MONTH,
    SUM(TOTAL_AMOUNT) AS TOTAL_SALES,
    COUNT(DISTINCT ORDER_ID) AS ORDER_COUNT
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES
GROUP BY
    YEAR,
    MONTH(ORDER_DATE);



-- V_SALES_BY_CUSTOMER
CREATE OR REPLACE VIEW RETAIL_ANALYTICS.GOLD.V_SALES_BY_CUSTOMER AS
SELECT
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME,
    c.COUNTRY,
    COUNT(DISTINCT f.ORDER_ID) AS ORDER_COUNT,
    SUM(f.QUANTITY) AS UNITS_PURCHASED,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_SALES
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES f
JOIN RETAIL_ANALYTICS.GOLD.DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.FIRST_NAME,
    c.LAST_NAME,
    c.COUNTRY;



-- COMMANDS

SELECT *
FROM RETAIL_ANALYTICS.GOLD.V_SALES
LIMIT 10;


SELECT *
FROM RETAIL_ANALYTICS.GOLD.V_SALES_BY_PRODUCT
ORDER BY TOTAL_SALES DESC
LIMIT 10;


SELECT *
FROM RETAIL_ANALYTICS.GOLD.V_SALES_BY_CUSTOMER
ORDER BY TOTAL_SALES DESC
LIMIT 10;


SELECT
    SUM(TOTAL_AMOUNT) AS FACT_TOTAL_SALES
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES;


SELECT
    SUM(TOTAL_SALES) AS VIEW_TOTAL_SALES
FROM RETAIL_ANALYTICS.GOLD.V_SALES_BY_PRODUCT;


SELECT
    SUM(TOTAL_SALES) AS MONTHLY_TOTAL
FROM RETAIL_ANALYTICS.GOLD.V_SALES_BY_MONTH;