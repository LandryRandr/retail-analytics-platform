CREATE OR REPLACE PROCEDURE RETAIL_ANALYTICS.SILVER.RUN_SILVER_INGESTION()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN

    CALL RETAIL_ANALYTICS.SILVER.REFRESH_EXTERNAL_TABLES();

    CALL RETAIL_ANALYTICS.SILVER.PROCESS_NEW_SILVER_FILES();

    RETURN 'Silver ingestion completed successfully';

END;
$$;


