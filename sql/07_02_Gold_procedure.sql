

-- GOLD PROCEDURE - FACT SALES
CREATE OR REPLACE PROCEDURE RETAIL_ANALYTICS.GOLD.PROCESS_NEW_GOLD_FILES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN

    /* =========================================================
       1. DIM_CUSTOMER
       ========================================================= */

    INSERT INTO RETAIL_ANALYTICS.GOLD.DIM_CUSTOMER (
        CUSTOMER_ID,
        FIRST_NAME,
        LAST_NAME,
        EMAIL,
        CITY,
        COUNTRY,
        SIGNUP_DATE
    )
    SELECT
        s.CUSTOMER_ID,
        s.FIRST_NAME,
        s.LAST_NAME,
        s.EMAIL,
        s.CITY,
        s.COUNTRY,
        s.SIGNUP_DATE
    FROM RETAIL_ANALYTICS.SILVER.CUSTOMERS s
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_ANALYTICS.GOLD.DIM_CUSTOMER g
        WHERE g.CUSTOMER_ID = s.CUSTOMER_ID
    );


    /* =========================================================
       2. DIM_PRODUCT
       ========================================================= */

    INSERT INTO RETAIL_ANALYTICS.GOLD.DIM_PRODUCT (
        PRODUCT_ID,
        PRODUCT_NAME,
        CATEGORY,
        UNIT_PRICE
    )
    SELECT
        s.PRODUCT_ID,
        s.PRODUCT_NAME,
        s.CATEGORY,
        s.UNIT_PRICE
    FROM RETAIL_ANALYTICS.SILVER.PRODUCTS s
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_ANALYTICS.GOLD.DIM_PRODUCT g
        WHERE g.PRODUCT_ID = s.PRODUCT_ID
    );


    /* =========================================================
       3. FACT_SALES
       ========================================================= */

    INSERT INTO RETAIL_ANALYTICS.GOLD.FACT_SALES (
        ORDER_ID,
        CUSTOMER_ID,
        PRODUCT_ID,
        ORDER_DATE,
        QUANTITY,
        UNIT_PRICE,
        TOTAL_AMOUNT,
        YEAR,
        QUARTER
    )
    SELECT
        o.ORDER_ID,
        o.CUSTOMER_ID,
        oi.PRODUCT_ID,
        o.ORDER_DATE,
        oi.QUANTITY,
        oi.UNIT_PRICE,
        oi.QUANTITY * oi.UNIT_PRICE AS TOTAL_AMOUNT,
        o.YEAR,
        o.QUARTER
    FROM RETAIL_ANALYTICS.SILVER.ORDERS o
    JOIN RETAIL_ANALYTICS.SILVER.ORDER_ITEMS oi
        ON o.ORDER_ID = oi.ORDER_ID
    WHERE NOT EXISTS (
        SELECT 1
        FROM RETAIL_ANALYTICS.GOLD.FACT_SALES f
        WHERE f.ORDER_ID = o.ORDER_ID
          AND f.PRODUCT_ID = oi.PRODUCT_ID
    );


    RETURN 'Gold ingestion completed successfully';

END;
$$;


CALL RETAIL_ANALYTICS.GOLD.PROCESS_NEW_GOLD_FILES();



-- VERIFICATION
SELECT
    'DIM_CUSTOMER' AS TABLE_NAME,
    COUNT(*) AS ROW_COUNT
FROM RETAIL_ANALYTICS.GOLD.DIM_CUSTOMER

UNION ALL

SELECT
    'DIM_PRODUCT',
    COUNT(*)
FROM RETAIL_ANALYTICS.GOLD.DIM_PRODUCT

UNION ALL

SELECT
    'FACT_SALES',
    COUNT(*)
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES;





SELECT COUNT(*)
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES;




