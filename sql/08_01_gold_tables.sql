-- VERIFICATION IF THE ORDER_ID + PRODUCT_ID IS ACTUALLY UNIQUE IN OUR SILVER ORDER_ITEMS
SELECT
    ORDER_ID,
    PRODUCT_ID,
    COUNT(*) AS CNT
FROM RETAIL_ANALYTICS.SILVER.ORDER_ITEMS
GROUP BY
    ORDER_ID,
    PRODUCT_ID
HAVING COUNT(*) > 1;


SELECT
    MAX(ORDER_ID) AS MAX_ORDER_ID
FROM RETAIL_ANALYTICS.SILVER.ORDERS;


SELECT COUNT(*) AS GOLD_ROWS
FROM RETAIL_ANALYTICS.GOLD.FACT_SALES;


-- TEST THE INCREMENTAL QUERY
SELECT
    o.ORDER_ID,
    o.CUSTOMER_ID,
    oi.PRODUCT_ID,
    o.ORDER_DATE,
    oi.QUANTITY,
    oi.UNIT_PRICE,
    oi.QUANTITY * oi.UNIT_PRICE AS TOTAL_AMOUNT,
    o.YEAR,
    o.QUARTER
FROM RETAIL_ANALYTICS.SILVER.ORDERS o
JOIN RETAIL_ANALYTICS.SILVER.ORDER_ITEMS oi
    ON o.ORDER_ID = oi.ORDER_ID
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_ANALYTICS.GOLD.FACT_SALES f
    WHERE f.ORDER_ID = o.ORDER_ID
      AND f.PRODUCT_ID = oi.PRODUCT_ID
);


